#!/usr/bin/env python3
"""Reject a cluster label that does not resolve to the generated names artifact.

A number on a map is not information; a name like "много пашни, много гари" is. The names are
generated by `scripts/build_cluster_names.py` from the interpretation fingerprints and the
committed vocabulary file, and nothing is allowed to name a cluster by hand. This check counts the
surfaces that show clusters, demands the artifact's names on each of them, and fails if a bare
«кластер 0»-style numbering is what the surfaces show, by the user's own reversal: the long
signature reads as an ambiguous list, so numbers go on the map and the meaning lives under the
legend. What must not happen is a signature typed into a hand-written shell instead of arriving
from the generated artifact.

Figures are live-drawn only after the figures page exists; until then this check says so rather
than pretending a surface was verified.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES_JSON = ROOT / "artifacts" / "interpretation" / "cluster_names.json"
NAMES_CSV = ROOT / "artifacts" / "interpretation" / "cluster_names.csv"
VOCAB = ROOT / "configs" / "cluster_name_vocabulary.yaml"
ASSIGNMENTS = ROOT / "artifacts" / "icvi" / "cluster_assignments.parquet"
CLUSTERING_CONFIG = ROOT / "configs" / "clustering.yaml"

sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402
import yaml  # noqa: E402

from sberindex import cluster  # noqa: E402


def shipped_cluster_ids() -> list[str]:
    """The cluster ids the names must cover, taken from the shipped partition rather than hardcoded.

    A checker written for 0,1,2 keeps passing while the partition has five clusters and the names cover four of
    them, or fails the moment a decision changes k for reasons that have nothing to do with the names being wrong.
    Reading the assignments makes the expectation follow the artifact it is supposed to guard.
    """
    asg = pd.read_parquet(ASSIGNMENTS)
    shipped = yaml.safe_load(CLUSTERING_CONFIG.read_text(encoding="utf-8")).get("shipped_method")
    sub = cluster.select_partition(asg, shipped)
    return sorted(str(int(c)) for c in sub["cluster"].dropna().unique())

# the language each surface is expected to name clusters in
SURFACES = {
    "index.html": "ru",
    "web/map/index.html": "ru",
    "web/map/full/index.html": "ru",
}
BUILDERS = [
    "scripts/build_landing.py",
    "scripts/build_map_full_page.py",
]
LABEL = re.compile(r"(?:кластер|cluster)\s+\d")
# Numbering may arrive at runtime, so the idiom counts as evidence too: «кластер " + p.cluster.
NUMBER = re.compile(r"(?:кластер|cluster)\s*(?:\d|[\"'`]?\s*\+)")
# Pages whose builder reads the names artifact; the BUILDERS loop below proves that claim.
ARTIFACT_BACKED = {"index.html", "web/map/full/index.html"}
# Hand-written sources: a signature appearing here was typed, not injected.
SHELLS = ("web/map/index.html", "web/map/full/shell.html", "web/presentation/shell.html")


def main() -> int:
    if not NAMES_JSON.exists():
        print("FAIL names artifact missing - run scripts/build_cluster_names.py")
        return 1
    names = json.loads(NAMES_JSON.read_text())
    expected_ids = shipped_cluster_ids()
    if sorted(names) != expected_ids:
        print(
            f"FAIL names artifact covers {sorted(names)}, expected {expected_ids} "
            "from the partition named in configs/clustering.yaml"
        )
        return 1
    if not VOCAB.exists():
        print("FAIL vocabulary file missing")
        return 1

    failures = 0
    for rel, lang in SURFACES.items():
        expected = names
        p = ROOT / rel
        if not p.exists():
            print(f"MISSING surface {rel}")
            failures += 1
            continue
        text = p.read_text()
        numbered = NUMBER.findall(text)
        if not numbered:
            print(f"FAIL {rel}: no cluster numbering, although the user asked for numbers")
            failures += 1
        injected = "const CLUSTER_NAMES = " in text or rel in ARTIFACT_BACKED
        present = [c for c, name in expected.items() if name in text]
        print(
            f"{rel} ({lang}): numbering {len(numbered)}, names found {len(present)}/3"
            + (" | names arrive from the artifact" if injected else "")
            + (" | numbers only, meaning lives elsewhere" if not present and numbered else "")
        )
        if present and not injected:
            print(f"FAIL {rel}: cluster signatures are on the surface but not from the artifact")
            failures += 1

    for rel in SHELLS:
        p = ROOT / rel
        if not p.exists():
            print(f"MISSING shell {rel} — nothing to compare the pages against")
            failures += 1
            continue
        src = p.read_text()
        typed = [c for c, name in names.items() if name in src]
        if typed:
            print(f"FAIL {rel}: cluster signatures typed into the shell: {typed}")
            failures += 1
        else:
            print(f"{rel}: no cluster signature typed into the shell")

    for rel in BUILDERS:
        p = ROOT / rel
        src = p.read_text() if p.exists() else ""
        if "cluster_names.json" not in src:
            print(f"FAIL {rel} does not read the names artifact")
            failures += 1

    figures_page = ROOT / "web" / "figures" / "index.html"
    figures_note = (
        "figures page not built yet - names there are unverified, not verified"
        if not figures_page.exists()
        else "figures page exists; its labels are covered by the surface check above once listed"
    )
    print("note:", figures_note)

    print(
        "CLUSTER NAMES CONTRACT VERIFIED"
        if failures == 0
        else f"CLUSTER NAMES CONTRACT FAILED ({failures})"
    )
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
