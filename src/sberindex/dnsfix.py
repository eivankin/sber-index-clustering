"""Resolve DNS over TCP when the container's resolver is dead.

Measured on 2026-10-06: ICMP to 8.8.8.8 works, HTTPS works once an IP is supplied
(`curl --resolve github.com:443:<ip>` got a real HTTP 400 from GitHub), but `getent hosts` fails for
every name and TCP/53 to 8.8.8.8 is blocked while TCP/53 to 1.1.1.1 is OPEN. So DNS is not down - it
is just unreachable through the configured nameservers, and /etc/resolv.conf is root-owned with no
sudo. The workaround is to query Cloudflare over TCP ourselves and feed the answers to the socket
layer.

The operator restored native resolution later the same day: `# Generated by resolvconf` with nameservers
111.88.96.51 / 111.88.96.50, `getent hosts github.com` answering again, and a plain
`ssh -T git@github.com` authenticating with no ProxyCommand. `install()` therefore probes the native
resolver first and only takes over when it genuinely fails - preferring a cached TCP answer over a
working system resolver would pin addresses that may have moved.

Usage: `from sberindex import dnsfix; dnsfix.install()` at the top of any network-using script.
"""

from __future__ import annotations

import socket
import struct

RESOLVERS = [("1.1.1.1", 53), ("1.0.0.1", 53)]
_CACHE: dict[str, str] = {}
_ORIGINAL = socket.getaddrinfo


def _measures_ipv6_egress() -> bool:
    """Asks the kernel whether it can send IPv6 at all, rather than assuming.

    Measured on this machine: `ip -6 route` shows only a link-local fe80::/64, and a fresh Python
    connection to earthengine.googleapis.com failed with "[Errno 101] Network is unreachable" while
    plain curl over IPv4 reached the same host. That is IPv6 being tried with nowhere to go, not Earth
    Engine being down. Only ENETUNREACH counts as no egress - a refused or timed-out attempt still means
    the kernel had a route, and filtering on that would break IPv6-capable environments.
    """
    probe = socket.socket(socket.AF_INET6, socket.SOCK_STREAM)
    probe.settimeout(1.0)
    try:
        probe.connect(("2001:4860:4860::8888", 53))
        return True
    except OSError as exc:
        return exc.errno != getattr(__import__("errno"), "ENETUNREACH", 101)
    finally:
        probe.close()


_IPV6_EGRESS = _measures_ipv6_egress()


def _native_but_ipv4_only(host, port, *args, **kwargs):
    """Uses the system resolver, but hands back IPv4 when IPv6 has nowhere to go."""
    infos = _ORIGINAL(host, port, *args, **kwargs)
    if not _IPV6_EGRESS:
        v4 = [info for info in infos if info[0] == socket.AF_INET]
        if v4:
            return v4
    return infos


def _build_query(name: str) -> bytes:
    qname = b"".join(bytes([len(lbl)]) + lbl.encode() for lbl in name.split(".")) + b"\x00"
    header = struct.pack(">HHHHHH", 0x1234, 0x0100, 1, 0, 0, 0)
    question = qname + struct.pack(">HH", 1, 1)  # type A, class IN
    return header + question


def _parse_answers(msg: bytes) -> list[str]:
    if len(msg) < 12:
        return []
    qd, an = struct.unpack(">HH", msg[4:8])
    pos = 12
    for _ in range(qd):  # skip questions
        while msg[pos] != 0:
            pos += msg[pos] + 1
        pos += 5
    ips = []
    for _ in range(an):
        while msg[pos] != 0:  # answer name (labels or a pointer)
            ln = msg[pos]
            if ln & 0xC0 == 0xC0:
                pos += 2
                break
            pos += ln + 1
        pos += 8  # type(2) class(2) ttl(4)
        rdlen = struct.unpack(">H", msg[pos : pos + 2])[0]
        pos += 2
        if rdlen == 4:
            ips.append(socket.inet_ntoa(msg[pos : pos + 4]))
        pos += rdlen
    return ips


def resolve(name: str, timeout: float = 6.0) -> str:
    if name in _CACHE:
        return _CACHE[name]
    q = _build_query(name)
    for host, port in RESOLVERS:
        try:
            with socket.create_connection((host, port), timeout=timeout) as s:
                s.sendall(struct.pack(">H", len(q)) + q)
                length_raw = s.recv(2)
                if len(length_raw) < 2:
                    continue
                length = struct.unpack(">H", length_raw)[0]
                msg = b""
                while len(msg) < length:
                    chunk = s.recv(length - len(msg))
                    if not chunk:
                        break
                    msg += chunk
                ips = _parse_answers(msg)
                if ips:
                    _CACHE[name] = ips[0]
                    return ips[0]
        except OSError:
            continue
    raise socket.gaierror(f"no A record for {name} via TCP resolvers")


def _getaddrinfo(host, port, family=0, type=0, proto=0, flags=0):
    if isinstance(host, str) and not host.replace(".", "").isdigit():
        try:
            ip = resolve(host)
        except socket.gaierror:
            return _ORIGINAL(host, port, family, type, proto, flags)
        host = ip
    return _ORIGINAL(host, port, family, type, proto, flags)


def _getaddrinfo_fallback(host, port, family=0, type=0, proto=0, flags=0):
    """Native first; our TCP answer only when the system resolver genuinely fails."""
    try:
        return _ORIGINAL(host, port, family, type, proto, flags)
    except OSError:
        if isinstance(host, str) and not host.replace(".", "").isdigit():
            try:
                host = resolve(host)
            except socket.gaierror:
                raise
        return _ORIGINAL(host, port, family, type, proto, flags)


def _native_works() -> bool:
    for probe in ("github.com", "api.github.com", "zenodo.org"):
        try:
            _ORIGINAL(probe, 443)
            return True
        except OSError:
            continue
    return False


def install() -> None:
    if _native_works():
        # Native resolution was restored by the operator, so the shim must not pin addresses.
        # It still filters IPv6 when the kernel has no route for it, which is what was measured here.
        socket.getaddrinfo = _native_but_ipv4_only
    else:
        socket.getaddrinfo = _getaddrinfo_fallback


def status() -> dict:
    # The values are not one type on purpose: a name that resolves holds a bool, and a name that fails holds the
    # exception text beside it, because "this host does not answer" is a result worth reading rather than a False
    # that hides why. The annotation says so; without it mypy read the first entry as the type of the whole dict.
    out: dict[str, object] = {"ipv6_egress": _IPV6_EGRESS}
    for name in [
        "code.earthengine.googleapis.com",
        "github.com",
        "zenodo.org",
        "storage.googleapis.com",
        "copernicus-dem-30m.s3.amazonaws.com",
        "files.isric.org",
        "eogdata.mines.edu",
    ]:
        try:
            out[name] = resolve(name)
        except Exception as exc:
            out[name] = f"FAIL {type(exc).__name__}: {str(exc)[:60]}"
    return out
